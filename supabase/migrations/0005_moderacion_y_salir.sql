create or replace function moderar_mensaje()
returns trigger
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_texto_normalizado text;
  v_palabras_encontradas text[];
  v_palabra text;
  v_count int;
begin
  v_texto_normalizado := lower(unaccent(NEW.text));

  select array_agg(distinct b.word) into v_palabras_encontradas
  from banned_words b
  where position(b.word in v_texto_normalizado) > 0;

  if v_palabras_encontradas is null then
    return NEW;
  end if;

  foreach v_palabra in array v_palabras_encontradas loop
    NEW.text := regexp_replace(NEW.text, v_palabra, repeat('*', length(v_palabra)), 'gi');
  end loop;

  insert into chat_warnings (chat_id, user_id, count)
  values (NEW.chat_id, NEW.sender_id, 1)
  on conflict (chat_id, user_id) do update set count = chat_warnings.count + 1
  returning count into v_count;

  if v_count >= 3 then
    delete from chats where id = NEW.chat_id;
    return null; -- cancela este insert — la sala ya no existe
  end if;

  return NEW;
end;
$$;

drop trigger if exists moderar_mensaje_trigger on messages;
create trigger moderar_mensaje_trigger
  before insert on messages
  for each row
  execute function moderar_mensaje();

-- Salir del chat = se borra para las dos familias (cascada limpia
-- chat_participants y messages). Solo puede salir quien sea participante.
create or replace function leave_chat(p_chat_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not exists (
    select 1 from chat_participants where chat_id = p_chat_id and user_id = auth.uid()
  ) then
    raise exception 'No sos participante de esta sala';
  end if;
  delete from chats where id = p_chat_id;
end;
$$;

revoke all on function leave_chat(uuid) from public;
grant execute on function leave_chat(uuid) to authenticated;
