-- Filtro de lenguaje inapropiado (multi-idioma) + salida real del chat.
--
-- 1) Salir del chat lo borra de verdad (RPC leave_chat, cascada limpia
--    mensajes y participantes) — antes "Salir" solo cerraba la vista local.
-- 2) Moderación de mensajes: trigger BEFORE INSERT censura palabras de una
--    lista de ~2.560 términos en 26 idiomas (dataset público LDNOOBW) y
--    lleva la cuenta de advertencias por (sala, usuario). Al 3er mensaje con
--    lenguaje inapropiado, la sala se borra sola (cancela ese insert, cierra
--    para las dos familias). No es 100% infalible (matching por substring,
--    sin lookahead complejo) — es un filtro razonable, no un sistema perfecto.

create extension if not exists unaccent with schema extensions;

create table if not exists banned_words (
  word text primary key,
  lang text not null
);

create table if not exists chat_warnings (
  chat_id uuid references chats(id) on delete cascade,
  user_id uuid not null,
  count int not null default 0,
  primary key (chat_id, user_id)
);

alter table banned_words enable row level security;
alter table chat_warnings enable row level security;
